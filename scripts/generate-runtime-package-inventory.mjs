#!/usr/bin/env node
// The canonical JSON supplies both browser ESM entries and its tracked mirror.
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const DEFAULT_ROOT = fileURLToPath(new URL('../', import.meta.url));
const CANONICAL = 'overlay/scratch-gui/src/lib/runtime-package-inventory.json';
const MIRROR = 'packages/scratch-gui/src/lib/runtime-package-inventory.json';
const MODULES = [
    'overlay/scratch-gui/src/lib/runtime-package-inventory.mjs',
    'packages/scratch-gui/src/lib/runtime-package-inventory.mjs'
];

export function renderInventoryModule (jsonText) {
    if (typeof jsonText !== 'string') throw new TypeError('Inventory source must be JSON text');
    JSON.parse(jsonText);
    // A JSON.parse string preserves JSON key semantics (including __proto__)
    // without introducing object-literal behavior or runtime module interop.
    const literal = JSON.stringify(jsonText).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
    return '/* Generated by scripts/generate-runtime-package-inventory.mjs; do not edit. */\n' +
        '/* eslint-disable max-len, quotes */\n' +
        `export default JSON.parse(${literal});\n`;
}

export async function syncInventoryModules ({root = DEFAULT_ROOT, check = false} = {}) {
    const canonical = await readFile(path.join(root, CANONICAL));
    const jsonText = new TextDecoder('utf-8', {fatal: true, ignoreBOM: true}).decode(canonical);
    const moduleBytes = Buffer.from(renderInventoryModule(jsonText), 'utf8');
    const outputs = [[MIRROR, canonical], ...MODULES.map(name => [name, moduleBytes])];
    const stale = [];
    for (const [name, expected] of outputs) {
        let current;
        try {
            current = await readFile(path.join(root, name));
        } catch (error) {
            if (error.code !== 'ENOENT') throw error;
        }
        if (!current || !current.equals(expected)) stale.push([name, expected]);
    }
    if (check && stale.length) {
        throw new Error('Runtime package inventory outputs are stale:\n' +
            stale.map(([name]) => `  ${name}`).join('\n'));
    }
    if (!check) {
        for (const [name, expected] of stale) {
            const target = path.join(root, name);
            await mkdir(path.dirname(target), {recursive: true});
            await writeFile(target, expected);
        }
    }
    return {checked: outputs.length, updated: check ? [] : stale.map(([name]) => name)};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--check')) {
        throw new Error('Usage: generate-runtime-package-inventory.mjs [--check]');
    }
    const check = args.includes('--check');
    const result = await syncInventoryModules({check});
    console.log(check ? 'Runtime package inventory: JSON mirror and both ESM entries are current.' :
        `Runtime package inventory: ${result.updated.length} generated output(s) updated.`);
}
