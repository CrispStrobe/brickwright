import assert from 'node:assert/strict';
import {chromium, webkit} from 'playwright';
import {openCodeActions, openCodeInfo} from './lib-code-actions.mjs';
import {typeIntoEditor} from './lib/type-into-editor.mjs';

const url = process.argv[2];
assert.ok(url, 'Pass the URL of the assembled Brickwright frontend');
const browser = process.env.BW_BROWSER_ENGINE === 'webkit' ?
    await webkit.launch() : await chromium.launch({executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH});
const page = await browser.newPage({viewport: {width: 1800, height: 1000}, locale: 'en-US', serviceWorkers: 'block'});
const languages = [
    ['🧩 Pseudo', /WHEN flag clicked/], ['🐍 Py', /def .*when_flag_clicked/],
    ['🟨 JS', /function .*when_flag_clicked/], ['🔧 C', /bw_structure/],
    ['📺 BAS', /REM generated by Brickwright/], ['λ fe', /\(print /],
    ['○ Tcl', /puts /], ['🔺 Forth', /: main/]
];
const pseudo = languages[0][0];
const message = 'Conversion Matrix Ready';
const code = page.locator('.cm-content').first();
const source = () => code.evaluate(element => element.cmTile.root.view.state.doc.toString());
const replaceSource = async text => {
    await code.click();
    await page.keyboard.press(process.platform === 'darwin' ? 'Meta+a' : 'Control+a');
    await page.keyboard.insertText(text);
    await page.waitForFunction(expected =>
        document.querySelector('.cm-content')?.cmTile.root.view.state.doc.toString() === expected, text);
};
const selectLanguage = async name => {
    const tab = page.getByRole('button', {name, exact: true});
    if (!(await tab.count())) {
        await page.getByTestId('bw-lang-more').click();
        await page.getByTestId('bw-lang-more-menu').getByRole('menuitem', {name: new RegExp(name)}).click();
    } else if (await tab.getAttribute('aria-pressed') !== 'true') await tab.click();
    await page.waitForFunction(label =>
        [...document.querySelectorAll('[data-testid="bw-lang-row"] button')]
            .some(element => element.getAttribute('aria-label') === label &&
                element.getAttribute('aria-pressed') === 'true'), name);
};
const action = async name => {
    await openCodeActions(page);
    await page.getByTestId('bw-code-actions-menu').getByRole('button', {name}).click();
};
const runtimeState = () => page.evaluate(() => {
    const runtime = window.__brickwrightStore.getState().scratchGui.vm.runtime;
    return {
        stage: runtime.getTargetForStage()?.id,
        device: runtime.stc?.device,
        blocks: runtime.targets.flatMap(target => Object.values(target.blocks._blocks))
    };
});
const apply = async () => {
    const before = (await runtimeState()).stage;
    await action(/To blocks$/i);
    await page.waitForFunction(previous => {
        const stage = window.__brickwrightStore.getState().scratchGui.vm.runtime.getTargetForStage();
        return stage && stage.id !== previous;
    }, before);
    await page.waitForFunction(() =>
        document.querySelector('[data-testid="bw-code-action-row"] button[aria-label$="To blocks"]')?.disabled === false);
};
const assertBlocks = async () => {
    const {device, blocks} = await runtimeState();
    assert.equal(device, undefined, 'The Scratch project must stay a Scratch project');
    assert.deepEqual(blocks.filter(block => ['event_whenflagclicked', 'data_setvariableto',
        'data_changevariableby', 'looks_say'].includes(block.opcode)).map(block => block.opcode).sort(),
    ['data_changevariableby', 'data_setvariableto', 'event_whenflagclicked', 'looks_say']);
    for (const block of blocks.filter(b => b.opcode.startsWith('data_'))) {
        if (block.fields.VARIABLE) assert.equal(block.fields.VARIABLE.value, 'total');
    }
    await page.evaluate(() => window.__brickwrightStore.getState().scratchGui.vm.greenFlag());
    await page.waitForFunction(() => {
        const runtime = window.__brickwrightStore.getState().scratchGui.vm.runtime;
        return runtime.targets.some(target =>
            Object.values(target.variables).some(variable => variable.name === 'total' && variable.value === 42));
    });
};

try {
    await page.addInitScript(() => {
        localStorage.setItem('bw-starter-v1-complete', '1');
        localStorage.setItem('bw-right-pane-hidden', '1');
    });
    await page.goto(url, {waitUntil: 'domcontentloaded'});
    await page.getByRole('tab', {name: 'Code', exact: true}).click();
    // gate-shapes-allow: startup readiness for conversions that check language/source, VM opcodes and the executed total of 42.
    await page.getByTestId('bw-lang-row').waitFor();
    await typeIntoEditor(page, `GLOBAL total\nWHEN flag clicked:\n  set total to 17\n  change total by 25\n  say "${message}"\n`);
    await apply();
    const sources = new Map();

    for (const [name, pattern] of languages) {
        await selectLanguage(name);
        await action(/^From blocks/i);
        const help = await openCodeInfo(page);
        await help.getByTestId('bw-conversion-report').filter({hasText: 'Blocks → Code'}).waitFor();
        await help.getByRole('button', {name: 'Close Code help'}).click();
        const generated = await source();
        assert.match(generated, pattern, name);
        assert.ok(generated.includes(message), name);
        sources.set(name, generated);
        await apply();
        assert.equal(await source(), generated, `${name} source changed during To blocks`);
        await assertBlocks();
        console.log(`Blocks → ${name} → Blocks ran and produced 42`);
    }

    if (!process.env.BW_SKIP_LANGUAGE_PAIRS) {
        for (const [from] of languages) {
            for (const [to, pattern] of languages) {
                if (from === to) continue;
                await selectLanguage(from);
                await replaceSource(sources.get(from));
                await selectLanguage(to);
                const generated = await source();
                assert.match(generated, pattern, `${from} → ${to}`);
                assert.ok(generated.includes(message), `${from} → ${to}`);
            }
            console.log(`${from} switched into the other seven Code languages`);
        }
    }
    await selectLanguage('🔩 ASM');
    const assembly = '; Local draft\nMOV AX, 7';
    await typeIntoEditor(page, assembly);
    await selectLanguage(pseudo);
    await typeIntoEditor(page, sources.get(pseudo));
    await apply();
    await action(/^From blocks/i);
    await selectLanguage('🔩 ASM');
    assert.equal(await source(), assembly);
    console.log('Editing Code and converting both ways retains the independent ASM draft.');

    await openCodeActions(page);
    const nqc = 'task main() { OnFwd(OUT_A); Wait(100); Off(OUT_A); }';
    await page.getByTestId('bw-open-file').locator('input').setInputFiles({
        name: 'draft.nqc', mimeType: 'text/plain', buffer: Buffer.from(nqc)
    });
    await selectLanguage('🧱 NQC');
    assert.equal(await source(), nqc);
    await openCodeActions(page);
    assert.equal(await page.getByTestId('bw-code-actions-menu').getByRole('button', {name: /To blocks$/i}).isDisabled(), true);
    await page.keyboard.press('Escape');
    await selectLanguage(pseudo);
    await typeIntoEditor(page, sources.get(pseudo));
    await selectLanguage('🧱 NQC');
    assert.equal(await source(), nqc);
    console.log('The NQC authoring path retains its source and has no reverse control.');

    await selectLanguage(pseudo);
    await typeIntoEditor(page, 'DEVICE MICROBIT\nWHEN flag clicked:\n  show text "Hello microbit"\n');
    await apply();
    await selectLanguage('🤖 micro:bit');
    assert.match(await source(), /Hello microbit/);
    await openCodeActions(page);
    assert.equal(await page.getByTestId('bw-code-actions-menu').getByRole('button', {name: /To blocks$/i}).isDisabled(), true);
    await page.keyboard.press('Escape');
    await selectLanguage(pseudo);
    assert.match(await source(), /^DEVICE MICROBIT/);
    console.log('The micro:bit MicroPython preview exports the program and returns to Pseudocode.');

} finally {
    await browser.close();
}
