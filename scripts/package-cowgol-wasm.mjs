/**
 * Vendor the CI-built offline Cowgol payload and regenerate its pins.
 *
 *   node scripts/package-cowgol-wasm.mjs --from DIR --gpl-manifest FILE
 *       DIR is the `cowgol-wasm-bundled` artifact of .github/workflows/cowgol-wasm.yml,
 *       FILE the manifest.json of its `cowgol-wasm-gpl` artifact. Every file is
 *       checked against its manifest before anything is written; the permissive
 *       payload replaces overlay/scratch-gui/src/lib/cowgol-wasm/dist and
 *       pins.js is rewritten. GPL BYTES ARE NEVER COPIED: only their hashes.
 *   node scripts/package-cowgol-wasm.mjs --check
 *       Verify the committed dist against pins.js: same file set, lengths and
 *       SHA-256, a permissive-only payload, and pins.js regenerated from
 *       dist/manifest.json exactly.
 */
import {createHash} from 'node:crypto';
import {mkdir, readFile, readdir, rename, rm, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const COWGOL_WASM_DIR = path.join(ROOT, 'overlay/scratch-gui/src/lib/cowgol-wasm');
const DIST = path.join(COWGOL_WASM_DIR, 'dist');
const PINS = path.join(COWGOL_WASM_DIR, 'pins.js');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
/** Never vendored here, whatever a manifest says (verify-no-gpl-in-build.mjs is the output gate). */
export const GPL_TOOLS = Object.freeze(['djlink', '64tass']);

export async function listFiles (directory, prefix = '') {
    const out = [];
    for (const entry of await readdir(directory, {withFileTypes: true})) {
        const rel = prefix + entry.name;
        if (entry.isDirectory()) out.push(...await listFiles(path.join(directory, entry.name), `${rel}/`));
        else if (entry.isFile()) out.push(rel);
        else throw new Error(`Cowgol WASM payload holds a non-regular entry: ${rel}`);
    }
    return out.sort();
}

/** The runtime's view of one manifest: tool entry points and the file table. */
export function pinsFromManifest (manifest, payload) {
    if (manifest?.schemaVersion !== 1 || manifest.format !== 'brickwright-cowgol-wasm' || manifest.payload !== payload ||
        !/^[0-9a-f]{40}$/.test(manifest.cowgolCommit || '')) {
        throw new Error(`Not a ${payload} Cowgol WASM manifest.`);
    }
    const tools = {};
    for (const [name, tool] of Object.entries(manifest.tools).sort()) {
        if ((payload === 'bundled') === GPL_TOOLS.includes(name)) throw new Error(`Tool ${name} is in the wrong payload.`);
        for (const file of [tool.module, tool.wasm]) {
            if (!manifest.files[file]) throw new Error(`Manifest lists ${name} without its file ${file}.`);
        }
        tools[name] = {module: tool.module, wasm: tool.wasm, license: tool.license};
    }
    const files = {};
    for (const [file, entry] of Object.entries(manifest.files).sort()) {
        if (file.includes('..') || file.startsWith('/') || !/^[0-9a-f]{64}$/.test(entry.sha256) ||
            !Number.isSafeInteger(entry.bytes)) throw new Error(`Invalid manifest entry: ${file}`);
        files[file] = {bytes: entry.bytes, sha256: entry.sha256};
    }
    return {payload, cowgolCommit: manifest.cowgolCommit, serviceCommit: manifest.serviceCommit,
        compiler: manifest.compiler, tools, files};
}

export async function verifyPayload (directory, manifest, {extra = ['manifest.json']} = {}) {
    const present = await listFiles(directory);
    const expected = [...Object.keys(manifest.files), ...extra].sort();
    if (JSON.stringify(present) !== JSON.stringify(expected)) {
        const missing = expected.filter(f => !present.includes(f));
        const unexpected = present.filter(f => !expected.includes(f));
        throw new Error(`Cowgol WASM payload file set differs (missing ${missing.join(', ') || 'none'}; unexpected ${unexpected.join(', ') || 'none'}).`);
    }
    for (const [file, entry] of Object.entries(manifest.files)) {
        const bytes = await readFile(path.join(directory, file));
        if (bytes.length !== entry.bytes || sha256(bytes) !== entry.sha256) throw new Error(`Cowgol WASM SHA-256 mismatch: ${file}`);
    }
}

export const renderPins = (bundled, gpl) => `// GENERATED by scripts/package-cowgol-wasm.mjs from the CI build manifests.
// Do not edit. The bundled payload is vendored in ./dist; the GPL payload is
// only described here (its bytes live at a separately configured origin).
export const COWGOL_WASM_PINS = Object.freeze(${JSON.stringify({bundled, gpl}, null, 2)});
`;

async function main () {
    const {values} = parseArgs({options: {from: {type: 'string'}, 'gpl-manifest': {type: 'string'}, check: {type: 'boolean'}}});
    if (values.check) {
        const manifest = JSON.parse(await readFile(path.join(DIST, 'manifest.json'), 'utf8'));
        await verifyPayload(DIST, manifest);
        const current = await readFile(PINS, 'utf8');
        const {COWGOL_WASM_PINS: pins} = await import(PINS);
        const bundled = pinsFromManifest(manifest, 'bundled');
        if (JSON.stringify(pins.bundled) !== JSON.stringify(bundled)) throw new Error('pins.js does not match dist/manifest.json.');
        if (current !== renderPins(bundled, pins.gpl)) throw new Error('pins.js is not the generator output.');
        console.log(`Cowgol WASM payload verified: ${Object.keys(manifest.files).length} files, Cowgol ${manifest.cowgolCommit}`);
        return;
    }
    if (!values.from || !values['gpl-manifest']) throw new Error('Use --from DIR --gpl-manifest FILE, or --check.');
    const from = path.resolve(values.from);
    const manifestBytes = await readFile(path.join(from, 'manifest.json'));
    const manifest = JSON.parse(manifestBytes);
    const gplManifest = JSON.parse(await readFile(path.resolve(values['gpl-manifest']), 'utf8'));
    const bundled = pinsFromManifest(manifest, 'bundled');
    const gpl = pinsFromManifest(gplManifest, 'gpl-origin');
    if (gpl.cowgolCommit !== bundled.cowgolCommit || gpl.compiler !== bundled.compiler) {
        throw new Error('The two payloads come from different builds.');
    }
    await verifyPayload(from, manifest);
    const staging = `${DIST}.staging`;
    await rm(staging, {recursive: true, force: true});
    for (const file of [...Object.keys(manifest.files), 'manifest.json']) {
        await mkdir(path.dirname(path.join(staging, file)), {recursive: true});
        await writeFile(path.join(staging, file), await readFile(path.join(from, file)));
    }
    await verifyPayload(staging, manifest);
    await rm(DIST, {recursive: true, force: true});
    await rename(staging, DIST);
    await writeFile(PINS, renderPins(bundled, gpl));
    console.log(`Vendored ${Object.keys(manifest.files).length} files into ${path.relative(ROOT, DIST)}; pinned ${Object.keys(gpl.files).length} GPL files by hash only.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => { console.error(`package-cowgol-wasm: ${error.message}`); process.exit(1); });
}
